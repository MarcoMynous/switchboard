export interface AppIconProps {
  name: string;
  className?: string;
  style?: CSSProperties;
  strokeWidth?: number;
}

export function AppIcon({ name, className = '', strokeWidth = 2 }: AppIconProps) {
  const IconComponent = ICON_MAP[name.trim()] ?? Sparkles;
  const cleanedClassName = className.replace(/\bmaterial-symbols-outlined\b/g, '').trim();

  return (
    <IconComponent
      aria-hidden="true"
      strokeWidth={strokeWidth}
      className={`w-[1em] h-[1em] shrink-0 inline-block ${cleanedClassName}`.trim()}
    />
  );
}
